class Handler(BaseHTTPRequestHandler):
    runs = {}

    def _send(self, obj, code=200, ctype="application/json"):
        body = obj if isinstance(obj, bytes) else (obj if isinstance(obj, str) else json.dumps(obj)).encode()
        self.send_response(code); self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body))); self.end_headers(); self.wfile.write(body)

    def log_message(self, *a):
        pass

    def do_GET(self):
        u = urlparse(self.path); q = parse_qs(u.query)
        if u.path in ("/", "/index.html"):
            return self._send(PAGE, ctype="text/html; charset=utf-8")
        if u.path == "/api/projects":
            return self._send({"version": VERSION, "home": HOME, "projects": projects()})
        if u.path == "/api/project":
            prj = load(q["slug"][0])
            return self._send({"project": prj, "doctor": doctor(prj), "dir": pdir(prj["slug"]), "home": HOME})
        if u.path == "/api/log":
            s = q["slug"][0]; r = self.runs.get(s)
            if not r: return self._send({"log": "", "running": False})
            return self._send({"log": r["buf"].getvalue(), "running": r["proc"].poll() is None})
        return self._send({"error": "not found"}, 404)

    def do_POST(self):
        u = urlparse(self.path)
        n = int(self.headers.get("Content-Length") or 0)
        b = json.loads(self.rfile.read(n) or "{}")
        try:
            if u.path == "/api/new":
                return self._send(cmd_new(b["slug"], b["title"], b.get("subtitle", ""), b.get("repo")))
            if u.path == "/api/save":
                prj = load(b["slug"])
                for k in ("title", "subtitle", "repo", "license", "description", "keywords", "plate_note"):
                    if k in b: prj[k] = b[k]
                return self._send(save(prj))
            if u.path == "/api/intake":
                return self._send(cmd_intake(b["slug"], b["dir"]))
            if u.path == "/api/bulk":
                return self._send({"matched": cmd_bulk(b["slug"], b["tsv"])})
            if u.path == "/api/setplate":
                return self._send(cmd_set(b["slug"], b["file"], **{b["key"]: b["value"]}))
            if u.path == "/api/build":
                return self._send(cmd_build(b["slug"]))
            if u.path == "/api/run":
                s = b["slug"]
                old = self.runs.get(s)
                if old and old["proc"].poll() is None:
                    return self._send({"error": "already running"}, 409)
                p = cmd_run(s, b["stage"], b.get("word"), b.get("override"))
                buf = io.StringIO(); self.runs[s] = {"proc": p, "buf": buf}
                threading.Thread(target=lambda: [buf.write(l) for l in p.stdout], daemon=True).start()
                return self._send({"started": True})
        except SystemExit as e:
            return self._send({"error": str(e)}, 400)
        except Exception as e:
            return self._send({"error": "%s: %s" % (type(e).__name__, e)}, 500)
        return self._send({"error": "not found"}, 404)


def serve(port=8710):
    os.makedirs(HOME, exist_ok=True)
    srv = ThreadingHTTPServer(("127.0.0.1", port), Handler)
    print("matba %s — http://127.0.0.1:%d   projects: %s" % (VERSION, port, HOME))
    print("Ctrl-C to stop. Nothing pushes or mints without you typing the gate word.")
    try: srv.serve_forever()
    except KeyboardInterrupt: print("\nstopped.")


def main(argv):
    if len(argv) < 2:
        print(__doc__); return 0
    c = argv[1]
    if c == "serve":
        return serve(int(argv[2]) if len(argv) > 2 else 8710)
    if c == "new":
        t = argv[argv.index("--title") + 1] if "--title" in argv else argv[2]
        s = argv[argv.index("--subtitle") + 1] if "--subtitle" in argv else ""
        r = argv[argv.index("--repo") + 1] if "--repo" in argv else None
        print(json.dumps(cmd_new(argv[2], t, s, r), indent=2)); return 0
    if c == "intake":
        print(json.dumps(cmd_intake(argv[2], argv[3]), indent=2)); return 0
    if c == "bulk":
        tsv = open(argv[3]).read() if len(argv) > 3 else sys.stdin.read()
        print("%d rows matched" % cmd_bulk(argv[2], tsv)); return 0
    if c == "plates":
        for i, p in enumerate(load(argv[2])["plates"], 1):
            print("%2d  %-34s %-28s %-18s %s" % (i, p["file"], p["slug"], p["part"],
                                                 "COVER" if p.get("cover") else p["title"][:40]))
        return 0
    if c == "set":
        kw = {}
        for k in ("slug", "title", "subtitle", "part", "topics", "lead", "explanation"):
            if "--" + k in argv: kw[k] = argv[argv.index("--" + k) + 1]
        if "--cover" in argv: kw["cover"] = True
        print(json.dumps(cmd_set(argv[2], argv[3], **kw), indent=2)); return 0
    if c == "doctor":
        f = doctor(load(argv[2]))
        print("\n".join("FAIL " + x for x in f) if f else "no failures"); return 1 if f else 0
    if c == "build":
        r = cmd_build(argv[2]); print(json.dumps(r, indent=2)); return 0 if r["ok"] else 1
    if c == "run":
        p = cmd_run(argv[2], argv[3], override="--override-rehearsal" in argv)
        for line in p.stdout: sys.stdout.write(line)
        return p.wait()
    print("unknown command: " + c); return 2


if __name__ == "__main__":
    try:
        rc = main(sys.argv)
    except BrokenPipeError:                     # `matba build | grep -q ...` closes the pipe early
        try: sys.stdout.close()
        except Exception: pass
        os._exit(0)
    except KeyboardInterrupt:
        print(); rc = 130
    try:
        sys.stdout.flush()
    except BrokenPipeError:
        os._exit(rc or 0)
    sys.exit(rc)
