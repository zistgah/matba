cov = os.path.basename(cfg["meta"]["cover"])
if not os.path.exists(os.path.join(d, cfg["meta"]["cover"])): bad("cover missing")
if cov in srcs: bad("cover is also a chapter figure")
for o in set(os.listdir(os.path.join(d, "assets/figures"))) - srcs - {cov}:
    if o.endswith(".ots"): continue
    bad("undeclared file in assets/figures (it WILL be minted): " + o)
for v in ("chatgpt", "gemini", "claude", "openai", "anthropic"):
    if v in json.dumps(cfg).lower(): bad("AI vendor named in a text layer: " + v)
print("  config/content/figure triangle: " + ("OK" if ok else "FAILED"))
