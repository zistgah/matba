def cmd_run(slug, stage, word=None, override=False, cwd=None):
    """Drive the generated seeder. Gates are answered by the typed word, never bypassed."""
    prj = load(slug); d = pdir(slug)
    sp = os.path.join(d, "seed_%s.sh" % prj["slug"])
    if not os.path.exists(sp):
        raise SystemExit("build first: matba build " + slug)
    args = ["bash", sp]
    if stage == "push": args.append("--push")
    elif stage == "mint":
        args.append("--mint")
        if override: args.append("--override-rehearsal")
    work = cwd or os.path.join(d, "work"); os.makedirs(work, exist_ok=True)
    shutil.copy2(sp, work); shutil.copy2(os.path.join(d, "%s.tar" % prj["slug"]), work)
    p = subprocess.Popen(["bash", os.path.basename(sp)] + args[2:], cwd=work,
                         stdin=subprocess.PIPE if word else None,
                         stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, bufsize=1)
    if word:                                   # web path: answer the gates, never bypass them
        p.stdin.write(word + "\n")            # PUSH gate
        if stage == "mint":
            p.stdin.write("MINT %s\n" % prj["slug"])
        p.stdin.close()
    return p


