def slugify(s):
    s = re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")
    return re.sub(r"-+", "-", s) or "untitled"


def sha256(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 16), b""):
            h.update(b)
    return h.hexdigest()


def pdir(slug):
    return os.path.join(HOME, slug)


def load(slug):
    p = os.path.join(pdir(slug), "project.json")
    if not os.path.exists(p):
        raise SystemExit("no such project: %s (matba new %s)" % (slug, slug))
    return json.load(open(p))


def save(prj):
    d = pdir(prj["slug"]); os.makedirs(d, exist_ok=True)
    json.dump(prj, open(os.path.join(d, "project.json"), "w"), indent=2, ensure_ascii=False)
    return prj


def projects():
    if not os.path.isdir(HOME):
        return []
    out = []
    for s in sorted(os.listdir(HOME)):
        if os.path.exists(os.path.join(HOME, s, "project.json")):
            try: out.append(json.load(open(os.path.join(HOME, s, "project.json"))))
            except Exception: pass
    return out


def cmd_new(slug, title, subtitle="", repo=None, author="Abhishek Choudhary",
            affil="AyeAI", orcid="0009-0002-0684-8320", license="CC-BY-SA-4.0"):
    slug = slugify(slug)
    d = pdir(slug)
    for sub in ("posters", "payload/content", "payload/posters", "config", "metadata", "overlays"):
        os.makedirs(os.path.join(d, sub), exist_ok=True)
    prj = {"slug": slug, "title": title, "subtitle": subtitle,
           "repo": repo or "zistgah/" + slug, "author": author, "affiliation": affil,
           "orcid": orcid, "license": license, "template": "zistgah/kitab",
           "description": "", "keywords": [], "related": [],
           "cover": None, "parts": [], "plates": [], "created": time.strftime("%Y-%m-%dT%H:%M:%SZ")}
    save(prj)
    return prj


def cmd_intake(slug, src):
    """Copy images in, hash once, refuse duplicate bytes, keep the operator's filename."""
    prj = load(slug); d = pdir(slug)
    if not os.path.isdir(src):
        raise SystemExit("not a directory: " + src)
    seen = {p["sha256"]: p["file"] for p in prj["plates"] if p.get("sha256")}
    added, dupes = [], []
    for name in sorted(os.listdir(src)):
        if not name.lower().endswith((".png", ".jpg", ".jpeg", ".webp")):
            continue
        s = os.path.join(src, name)
        h = sha256(s)
        if h in seen:
            dupes.append((name, seen[h])); continue
        shutil.copy2(s, os.path.join(d, "posters", name))
        seen[h] = name
        prj["plates"].append({"file": name, "sha256": h, "slug": slugify(os.path.splitext(name)[0]),
                              "title": "", "subtitle": "", "lead": "", "explanation": "",
                              "topics": [], "part": "", "cover": False})
        added.append(name)
    save(prj)
    return {"added": added, "duplicates": dupes, "total": len(prj["plates"])}


def cmd_bulk(slug, tsv):
    """slug-or-filename <TAB> title <TAB> subtitle <TAB> part <TAB> topics(;) [<TAB> lead <TAB> explanation]"""
    prj = load(slug); by = {}
    for p in prj["plates"]:
        by[p["file"]] = p; by[p["slug"]] = p; by[os.path.splitext(p["file"])[0]] = p
    hit = 0
    for line in tsv.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        col = [c.strip() for c in re.split(r"\t|\s*\|\s*", line)]
        p = by.get(col[0])
        if not p:
            continue
        hit += 1
        for i, k in enumerate(("", "title", "subtitle", "part", "topics", "lead", "explanation"), 0):
            if i == 0 or i >= len(col) or not col[i]:
                continue
            p[k] = [t.strip() for t in col[i].split(";") if t.strip()] if k == "topics" else col[i]
    save(prj)
    return hit


def cmd_set(slug, plate, **kw):
    prj = load(slug)
    for p in prj["plates"]:
        if plate in (p["file"], p["slug"], os.path.splitext(p["file"])[0]):
            if kw.get("cover"):
                for q in prj["plates"]:
                    q["cover"] = False
                prj["cover"] = p["file"]
            for k, v in kw.items():
                if v is None:
                    continue
                p[k] = [t.strip() for t in v.split(";")] if k == "topics" and isinstance(v, str) else v
            save(prj); return p
    raise SystemExit("no such plate: " + plate)


def doctor(prj):
    """Every failure here is one that actually reached a DOI once."""
    f = []
    plates = prj["plates"]
    chaps = [p for p in plates if not p.get("cover")]
    cover = [p for p in plates if p.get("cover")]
    if not plates: f.append("no plates: run intake")
    if not cover: f.append("no cover chosen (matba set <slug> <plate> --cover)")
    if len(cover) > 1: f.append("more than one cover")
    for p in chaps:
        if not p["title"]: f.append("no title: " + p["file"])
        if not p["part"]: f.append("no part: " + p["file"])
        if not p["lead"]: f.append("no lead paragraph: " + p["file"])
    slugs = [p["slug"] for p in plates]
    for s in {x for x in slugs if slugs.count(x) > 1}: f.append("duplicate slug: " + s)
    hs = [p["sha256"] for p in plates]
    for h in {x for x in hs if hs.count(x) > 1}:
        f.append("duplicate bytes: " + ", ".join(p["file"] for p in plates if p["sha256"] == h))
    blob = json.dumps(prj).lower()
    for v in ("chatgpt", "gemini", "claude", "openai", "anthropic"):
        if v in blob: f.append("AI vendor named in a text layer: " + v)
    if not prj["title"]: f.append("no book title")
    if not prj.get("description"): f.append("no description — Zenodo will show an empty abstract")
    if "/" not in prj["repo"]: f.append("repo must be owner/name")
    return f


