#!/usr/bin/env python3
"""matba (مطبع) — the press.

One tool for the whole path: posters in, book out, sealed, pushed, minted.
Local-first, stdlib only, no backend, no network except what git/gh/misty do themselves.

    python3 matba.py serve                     # web UI on http://127.0.0.1:8710
    python3 matba.py new <slug> --title "..."  # CLI mirrors every web action
    python3 matba.py intake <slug> <dir>
    python3 matba.py plates <slug>             # show / edit the plate table
    python3 matba.py build <slug>              # payload + seeder + selftest
    python3 matba.py run <slug> stage|push|mint

It does NOT reimplement git, gh or misty. It writes ONE generic seeder (the same engine that
minted zenodo.21917807, .21928710 and .21930508) and drives it. Typed gates are unchanged:
nothing pushes or mints without the operator typing the word.
"""
