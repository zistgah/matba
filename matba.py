import json, os, sys
d, slug = sys.argv[1], sys.argv[2]; ok = True
def bad(m):
    global ok; ok = False; print("  FAIL " + m)
cfg = json.load(open(os.path.join(d, "config/book.config.json")))
if cfg["meta"]["repo"] != slug: bad("meta.repo != " + slug)
srcs = set()
for c in cfg["structure"]["chapters"]:
    p = os.path.join(d, c["source"])
    if not os.path.exists(p): bad("missing " + c["source"]); continue
